export type NodeKey = 'a' | 'b' | 'a1' | 'a2' | 'b1' | 'b2' | 'a1x' | 'a2x' | 'b1x' | 'b2x';

export interface SkillNode {
  id: string; // `${тип}:${ключ}`, корень — `${тип}:root`
  type: OrbType;
  key: NodeKey;
  name: string;
  desc: string;
  effect: TypeMods;
  parent: string; // id родителя (корень или узел выше)
  exclusive: string[]; // id узлов, которые закрываются при открытии этого (выбор пути)
  tier: 1 | 2 | 3;
  col: number; // колонка на схеме: 0..6 (шаг 42 px), см. TREE_COLS
  row: number; // строка на схеме: 1..3 (корень — 0)
  points: number; // очки прокачки
  coins: number; // монеты
}

export const ROOT_SUFFIX = 'root';
export const rootId = (t: OrbType) => `${t}:${ROOT_SUFFIX}`;

// Схема одна на все шарики: позиции узлов и связи.
