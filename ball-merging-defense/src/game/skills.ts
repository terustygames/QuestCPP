// ============================================================
// ДЕРЕВЬЯ НАВЫКОВ ШАРИКОВ (мета-прокачка между забегами).
//
// У каждого из двенадцати шариков — своё дерево из 11 узлов (+ корень):
//
//            [корень — открыт всегда]
//            /        |        \
//       A (выбор)  AUTO (авто-линия)  B (выбор)     ← ряд 1
//       /    \                       /    \
//     A1      A2                  B1      B2        ← ряд 2: развилки A1/A2, B1/B2
//      |        |                   |        |
//    A1x      A2x                 B1x      B2x      ← ряд 3: концовки
//
// Два уровня выбора на каждом пути: сторона (A или B) и ветка внутри неё
// (A1 или A2, B1 или B2). Взаимоисключающие узлы закрываются друг другом
// до сброса дерева (статус «blocked»). Узел авто-линии — один на дерево,
// его эффект разный у каждого шарика: он усиливает линию, которую игрок
// провёл и которая стреляет сама (см. engine.ts, авто-линия).
//
// Стоимость в очках прокачки растёт: следующий узел стоит на одно ОП больше
// предыдущего (n-й открытый узел дерева стоит n ОП). Очки привязаны к шарику:
// тратятся только на его дерево. Монеты — общие, стоимость по ряду.
// Все цифры дерева — здесь. Движок читает их через TypeMods (Engine.m()).
// ============================================================

import type { OrbType } from './config';

// Ключи эффектов, которые понимает движок (см. Engine.m() и hitDmg()).
//  dmg       — плоский урон основного попадания (+N)
//  dmgPct    — процент урона основного попадания (0.15 = +15%)
//  crit      — шанс критического попадания: урон ×2 (0.1 = 10%)
//  shots     — снарядов в залпе (+N)
//  cd        — перезарядка, секунды (−0.1 = быстрее)
//  combo     — бонус линии: урон каждому шарику линии (+N)
//  radius    — радиус эффекта, px (осколки огня, цепь молнии, взрыв сверхновой)
//  chain     — целей цепи молнии (+N)
//  pierce    — врагов, которых пробивает пробой (+N)
//  dur       — длительность эффекта, секунды (лёд, яд, паралич, метка)
//  slow      — замедление врага: отрицательное значение = сильнее (−0.05)
//  dps       — урон во времени в секунду: яд, метка (+N)
//  stacks    — максимум стаков яда / меток на одном враге (+N)
//  needles   — игл при лопании шипастого (+N)
//  splash    — урон осколков огня соседним врагам (+N)
//  ess       — эссенция: шипастый — за взрыв, вампир — за каждое попадание (+N)
//  amp       — множитель усиления соседей усилителя (+N к ×2)
//  drain     — высасывание эссенции меткой: +N к коэффициенту (1 + drain)
//  autoGap   — авто-линия выдерживает пропажу N шариков (сумма по колоде)
//  autoPct   — урон авто-залпов, в процентах (20 = +20%)
//  autoShots — снарядов в каждом авто-залпе (+N)
//  autoCd    — авто-залп сокращает перезарядку на N секунд

export type ModKey =
  | 'dmg'
  | 'dmgPct'
  | 'crit'
  | 'shots'
  | 'cd'
  | 'combo'
  | 'radius'
  | 'chain'
  | 'pierce'
  | 'dur'
  | 'slow'
  | 'dps'
  | 'stacks'
  | 'needles'
  | 'splash'
  | 'ess'
  | 'amp'
  | 'drain'
  | 'autoGap'
  | 'autoPct'
  | 'autoShots'
  | 'autoCd';

export type TypeMods = Partial<Record<ModKey, number>>;

// Тиры: ряд 1 — 40 монет, ряд 2 — 80, ряд 3 — 150; авто-узел — 60.
export const TIER_COINS: Record<1 | 2 | 3 | 0, number> = { 0: 60, 1: 40, 2: 80, 3: 150 };

export type NodeKey = 'auto' | 'a' | 'b' | 'a1' | 'a2' | 'b1' | 'b2' | 'a1x' | 'a2x' | 'b1x' | 'b2x';

export interface SkillNode {
  id: string; // `${тип}:${ключ}`, корень — `${тип}:root`
  type: OrbType;
  key: NodeKey;
  name: string;
  desc: string;
  effect: TypeMods;
  parent: string; // id родителя (корень или узел выше)
  exclusive: string[]; // id взаимоисключающих узлов (развилка)
  tier: 0 | 1 | 2 | 3; // 0 — авто-узел
  col: number; // колонка на схеме: 0..3 (шаг 90 px), см. TREE_COLS
  row: number; // строка на схеме: 1..3 (корень — 0)
  coins: number; // монеты (общие)
}

export const ROOT_SUFFIX = 'root';
export const rootId = (t: OrbType) => `${t}:${ROOT_SUFFIX}`;

// Очки прокачки, которые стоит следующий узел дерева, если уже открыто opened узлов.
// Растёт на одно ОП с каждым узлом: 1, 2, 3, ... (всего 66 ОП за полное дерево).
export function nextNodePoints(opened: number): number {
  return opened + 1;
}

// Очки, которые возвращает сброс дерева при opened открытых узлах (сумма всех оплат).
export function refundPointsFor(opened: number): number {
  return (opened * (opened + 1)) / 2;
}

