// Сборка узлов из схемы и текстов. Узел — один на тип и ключ.
function buildTree(): SkillNode[] {
  const out: SkillNode[] = [];
  (Object.keys(TEXT) as OrbType[]).forEach((type) => {
    const idOf = (key: NodeKey | 'root') => (key === 'root' ? rootId(type) : `${type}:${key}`);
    TREE_SLOTS.forEach((s) => {
      const siblings = TREE_SLOTS.filter((o) => o.fork && o.parent === s.parent && o.key !== s.key);
      const exclusive = s.fork ? siblings.map((o) => idOf(o.key)) : [];
      const [name, desc, effect] = TEXT[type][s.key];
      out.push({
        id: idOf(s.key),
        type,
        key: s.key,
        name,
        desc,
        effect,
        parent: idOf(s.parent),
        exclusive,
        tier: s.tier,
        col: s.col,
        row: s.row,
        coins: TIER_COINS[s.tier],
      });
    });
  });
  return out;
}

export const SKILL_NODES: SkillNode[] = buildTree();
export const NODE_BY_ID: Record<string, SkillNode> = Object.fromEntries(SKILL_NODES.map((n) => [n.id, n]));
export const TREE_BY_TYPE = Object.fromEntries(
  (Object.keys(TEXT) as OrbType[]).map((t) => [t, SKILL_NODES.filter((n) => n.type === t)])
) as Record<OrbType, SkillNode[]>;

const fmt = (v: number) => String(Math.round(v * 100) / 100).replace('.', ',');
const signed = (v: number) => (v > 0 ? '+' : v < 0 ? '−' : '') + fmt(Math.abs(v));

export const MOD_TEXT: Record<ModKey, (v: number) => string> = {
  dmg: (v) => `урон ${signed(v)}`,
  dmgPct: (v) => `урон ${signed(v * 100)}%`,
  crit: (v) => `шанс двойного урона ${signed(v * 100)}%`,
  shots: (v) => `снарядов в залпе ${signed(v)}`,
  cd: (v) => `перезарядка ${signed(v)} с`,
  combo: (v) => `урон линии ${signed(v)} за шарик`,
  radius: (v) => `радиус ${signed(v)} px`,
  chain: (v) => `целей молнии ${signed(v)}`,
  pierce: (v) => `пробивает врагов ${signed(v)}`,
  dur: (v) => `длительность ${signed(v)} с`,
  slow: (v) => `замедление ${signed(-v * 100)}%`,
  dps: (v) => `урон во времени ${signed(v)} в секунду`,
  stacks: (v) => `стаков / меток на враге ${signed(v)}`,
  needles: (v) => `игл ${signed(v)}`,
  splash: (v) => `урон осколков ${signed(v)}`,
  ess: (v) => `эссенции ${signed(v)} за событие`,
  amp: (v) => `усиление соседей ${signed(v)}`,
  drain: (v) => `высасывание эссенции ${signed(v * 100)}%`,
  autoGap: (v) => `авто-линия выдерживает пропажу шариков ${signed(v)}`,
  autoPct: (v) => `урон авто-линии ${signed(v)}%`,
  autoShots: (v) => `снарядов авто-залпа ${signed(v)}`,
  autoCd: (v) => `авто-залп: перезарядка −${fmt(v)} с`,
};

// Список строк для панелей: «урон +1», «перезарядка −0,1 с» и т.д.
export function describeMods(mods: TypeMods | undefined): string[] {
  if (!mods) return [];
  const out: string[] = [];
  (Object.keys(MOD_TEXT) as ModKey[]).forEach((k) => {
    const v = mods[k];
    if (v !== undefined && Math.abs(v) > 1e-9) out.push(MOD_TEXT[k](v));
  });
  return out;
}
